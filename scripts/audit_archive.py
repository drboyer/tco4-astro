#!/usr/bin/env python3
"""Generate an offline, repeatable article/media/editorial review inventory."""
import json
import re
import subprocess
from pathlib import Path
from urllib.parse import urlsplit, unquote

ROOT = Path(__file__).resolve().parents[1]


def audit(root=ROOT):
    data = json.loads((root / 'scripts/ghost-export.json').read_text())['db'][0]['data']
    repairs = json.loads((root / 'scripts/archive-repairs.json').read_text())
    rows = []
    originals = {post['slug']: post for post in data['posts']}
    current = json.loads(subprocess.check_output(['node', str(ROOT / 'scripts/read-content.mjs'), str(root)], text=True, cwd=ROOT))
    for meta in sorted(current, key=lambda p: p['pubDate'], reverse=True):
        slug = meta['slug']
        post = originals.get(slug)
        body = meta['body']
        images = [a or b for a, b in re.findall(r'!\[[^\]]*\]\(([^)]+)\)|<img[^>]*src=[\"\x27]([^\"\x27]+)', body)]
        if meta.get('image'):
            images.append(meta['image'])
        local, external = [], []
        for image in sorted(set(images)):
            url = urlsplit(image)
            if url.netloc and url.netloc != 'thecloudonline.net':
                external.append(image)
            else:
                local.append(url.path)
        missing = [path for path in local if not (root / 'public' / unquote(path).lstrip('/')).is_file()]
        original = (post.get('markdown') or '') if post else body
        issues = [f'Missing media: {path}' for path in missing]
        if 'storify.com' in original:
            issues.append('Storify memorial contents unrecovered; approve fallback or supply archived contents')
        if '<iframe' in body:
            issues.append('Review retained YouTube playback; direct watch links provided')
        if '<table' in body:
            issues.append('Review historical table layout at mobile widths')
        if 'twitter-tweet' in original:
            issues.append('Review Twitter/X widget rendering and blockquote/source-link fallbacks with scripts blocked')
        if external:
            issues.append('External image availability remains a third-party dependency')
        if slug in ('samplepost', 'untitled'):
            issues.append('Historical slug belongs to a substantive article; retained pending editorial decision')
        if 'https://thecloudonline.net/drought-relief' in body:
            issues.append('Drought-relief URL redirects to the article about the retired project')
        rows.append({
            'slug': slug, 'title': meta['title'], 'url': f'/blog/{slug}/', 'date': meta['pubDate'],
            'date_matches_export': meta['pubDate'] == post['published_at'][:10] if post else None,
            'local_images': local, 'missing_images': missing, 'external_images': external,
            'repairs': list(dict.fromkeys(repair['reason'] for repair in repairs.get(slug, []))),
            'review': issues, 'editorial_approval': 'pending',
        })
    (root / 'docs/archive-review.json').write_text(json.dumps(rows, indent=2, ensure_ascii=False) + '\n')
    lines = ['# Article review inventory', '', 'Generated by `npm run audit:archive`. Technical checks do not replace editorial or browser sign-off.', '',
             '| Article / preserved URL | Date | Local images | Repairs and review | Approval |',
             '| --- | --- | --- | --- | --- |']
    for row in rows:
        notes = row['repairs'] + row['review'] or ['No complex embeds; review prose and presentation']
        notes = '; '.join(notes).replace('|', '\\|')
        lines.append(f"| [{row['title']}]({row['url']}) | {row['date']} | {len(row['local_images']) - len(row['missing_images'])}/{len(row['local_images'])} available | {notes} | Pending |")
    lines += ['', 'Current Markdown is authoritative. Original imported article bodies remain in the sanitized export; migration-time presentation repairs are versioned in `scripts/archive-repairs.json`.',
              '', 'Descriptions were regenerated to retain Markdown link labels. Embedded image alternative text is preserved; empty descriptions still require an editorial pass.',
              '', 'See `external-links-review.json` for network observations. HTTP failures and timeouts are review candidates, not proof a resource is permanently unavailable.']
    (root / 'docs/ARTICLE_REVIEW.md').write_text('\n'.join(lines) + '\n')
    print(f"Audited {len(rows)} articles; {sum(len(row['missing_images']) for row in rows)} missing image references")
    return rows


if __name__ == '__main__':
    audit()
